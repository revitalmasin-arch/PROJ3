def teach_hebrew_word():
    """
    Teaches a new Hebrew word: prints the word, its pronunciation, and its meaning in English.
    """
    word = "שלום"
    transliteration = "Shalom"
    meaning = "peace, hello, goodbye"

    print("Today's Hebrew word is:")
    print(f"Hebrew: {word}")
    print(f"Pronunciation: {transliteration}")
    print(f"Meaning: {meaning}")

if __name__ == "__main__":
    teach_hebrew_word()